BUILDERS = (
    transportation_planning,
    transportation,
    traffic_engineering,
    traffic_safety,
    data_mining,
)


def main(argv: list[str] | None = None) -> int:
    args = argv if argv is not None else sys.argv[1:]
    root = Path(args[0]) if args else Path(__file__).resolve().parents[5] / "Courses"
    if not root.is_dir():
        print(f"پوشهٔ دروس پیدا نشد: {root}", file=sys.stderr)
        return 1
    for build in BUILDERS:
        manifest = build(root)
        if not manifest.directory.is_dir():
            print(f"  رد شد (پوشه نیست): {manifest.directory.name}")
            continue
        path = write_manifest(manifest)
        print(f"  نوشته شد: {path.relative_to(root.parent)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
